package domain

import (
	"testing"
	"time"
)

func TestParsePromisedDueRecognisesExplicitDeadlines(t *testing.T) {
	loc, err := time.LoadLocation("Europe/Moscow")
	if err != nil {
		t.Fatal(err)
	}
	// Среда, 2 сентября 2026, 11:00 по Москве.
	from := time.Date(2026, 9, 2, 11, 0, 0, 0, loc)
	for _, test := range []struct {
		text   string
		want   time.Time
		phrase string
	}{
		{"Проверю расписание и отвечу через десять минут.", from.Add(10 * time.Minute), "через десять минут"},
		{"Свяжусь с мастером и напишу вам через полчаса.", from.Add(30 * time.Minute), "через полчаса"},
		{"Уточню адрес выезда и напишу через час.", from.Add(time.Hour), "через час"},
		{"Перезвоню через 15 мин.", from.Add(15 * time.Minute), "через 15 мин"},
		{"Отвечу через два часа.", from.Add(2 * time.Hour), "через два часа"},
		{"Подготовлю расчёт и пришлю его в течение часа.", from.Add(time.Hour), "в течение часа"},
		{"Сообщу в течение 20 минут.", from.Add(20 * time.Minute), "в течение 20 минут"},
		{"Проверю доступность специалиста и отвечу в течение дня.", time.Date(2026, 9, 2, 18, 0, 0, 0, loc), "в течение дня"},
		{"Уточню у специалиста и напишу сегодня до 18:00.", time.Date(2026, 9, 2, 18, 0, 0, 0, loc), "сегодня до 18:00"},
		{"Пришлю смету к 17 часам.", time.Date(2026, 9, 2, 17, 0, 0, 0, loc), "к 17 часам"},
		{"Согласую скидку и дам ответ завтра до полудня.", time.Date(2026, 9, 3, 12, 0, 0, 0, loc), "завтра до полудня"},
		{"Перезвоню вам завтра утром с ответом.", time.Date(2026, 9, 3, 10, 0, 0, 0, loc), "завтра утром"},
		{"Проверю заявку и отвечу не позднее завтра.", time.Date(2026, 9, 3, 12, 0, 0, 0, loc), "не позднее завтра"},
		{"Отправлю договор завтра к 09:30.", time.Date(2026, 9, 3, 9, 30, 0, 0, loc), "завтра к 09:30"},
		{"Отправлю договор сегодня после обеда.", time.Date(2026, 9, 2, 15, 0, 0, 0, loc), "сегодня после обеда"},
		{"Проверю наличие материалов и сообщу до конца дня.", time.Date(2026, 9, 2, 18, 0, 0, 0, loc), "до конца дня"},
		{"Подготовлю варианты времени и отправлю до вечера.", time.Date(2026, 9, 2, 18, 0, 0, 0, loc), "до вечера"},
		{"Проверю вашу оплату и подтвержу получение сегодня.", time.Date(2026, 9, 2, 18, 0, 0, 0, loc), "сегодня"},
		{"Вернусь с ответом в пятницу.", time.Date(2026, 9, 4, 12, 0, 0, 0, loc), "в пятницу"},
		{"Напишу в среду вечером.", time.Date(2026, 9, 9, 18, 0, 0, 0, loc), "в среду вечером"},
		{"Ёлку привезём через ПОЛЧАСА!", from.Add(30 * time.Minute), "через полчаса"},
	} {
		t.Run(test.text, func(t *testing.T) {
			due, ok := ParsePromisedDue(test.text, from, loc)
			if !ok || !due.At.Equal(test.want) || due.Phrase != test.phrase {
				t.Fatalf("ParsePromisedDue = %s / %q / %v; ожидалось %s / %q", due.At.In(loc), due.Phrase, ok, test.want, test.phrase)
			}
		})
	}
}

func TestParsePromisedDueFallsBackOnVagueOrPastDeadlines(t *testing.T) {
	loc, err := time.LoadLocation("Europe/Moscow")
	if err != nil {
		t.Fatal(err)
	}
	from := time.Date(2026, 9, 2, 19, 30, 0, 0, loc)
	for _, text := range []string{
		"Забронирую предварительное окно и подтвержу сообщением.",
		"Уточню длительность процедуры и вернусь с ответом.",
		"Передам вопрос руководителю и сообщу решение.",
		"Подготовлю памятку и отправлю следующим сообщением.",
		"Отвечу на следующей неделе.",
		"Сообщу 25 сентября после обеда.",
		"Напишу утром.",            // после 10:00 «утром» относится к другому дню
		"Ответим до 5.",            // без минут неоднозначно
		"Ответим сегодня до 18:00", // уже прошло
		"Проверю через 0 минут.",
		"Пришлю через год.",
		"",
	} {
		t.Run(text, func(t *testing.T) {
			if due, ok := ParsePromisedDue(text, from, loc); ok {
				t.Fatalf("неоднозначный срок разобран как %s (%q)", due.At.In(loc), due.Phrase)
			}
		})
	}
}
