// promiseScanExampleTurns разворачивает примеры в реплики чата: запрос пользователя и ответ ассистента.
var promiseScanExampleTurns = func() []map[string]string {
	turns := make([]map[string]string, 0, len(promiseScanExamples)*2)
	for _, example := range promiseScanExamples {
		conversation, err := json.Marshal(scanConversation{Messages: example.messages})
		if err != nil {
			panic(err)
		}
		ids := make([]string, len(example.decisions))
		classes := make([]string, len(example.decisions))
		for i, decision := range example.decisions {
			ids[i], classes[i] = decision.id, decision.class
		}
		turns = append(turns,
			map[string]string{"role": "user", "content": string(conversation)},
			map[string]string{"role": "assistant", "content": scanAnswerJSON(ids, classes)})
	}
	return turns
}()

// promiseScanConfirmTurns — те же примеры в обратном порядке: второй вариант прохода (agreedProbabilities). Порядок меняет то, что модель
// помнит последним, и тем самым ошибки пограничных сообщений первого варианта.
var promiseScanConfirmTurns = func() []map[string]string {
	reversed := make([]map[string]string, 0, len(promiseScanExampleTurns))
	for i := len(promiseScanExampleTurns) - 2; i >= 0; i -= 2 {
		reversed = append(reversed, promiseScanExampleTurns[i], promiseScanExampleTurns[i+1])
	}
	return reversed
}()

// scanAnswerJSON собирает объект {"m2":"promise",...} в порядке сообщений; карта Go хранила бы ключи по алфавиту («m10» раньше «m2»).
func scanAnswerJSON(ids []string, classes []string) string {
	var out strings.Builder
	out.WriteByte('{')
	for i, id := range ids {
		if i > 0 {
			out.WriteByte(',')
		}
		key, _ := json.Marshal(id)
		out.Write(key)
		out.WriteByte(':')
		value, _ := json.Marshal(classes[i])
		out.Write(value)
	}
	out.WriteByte('}')
	return out.String()
}
